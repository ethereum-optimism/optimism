    def git(self,root,*argv):
        return subprocess.check_output(['git',*argv],cwd=root).strip()

    def commit(self,root):
        self.git(root,'add','.')
        self.git(root,'-c','user.name=CI fixture','-c','user.email=ci-fixture@example.invalid','commit','-qm','Actual provenance fixture')
        return self.git(root,'rev-parse','HEAD').decode()

