    def write_locks(self,entries):
        (self.root/N.LOCK).write_text(''.join('['+fork+']\n'+''.join(k+' = '+json.dumps(v)+'\n' for k,v in entry.items()) for fork,entry in entries.items()))

    def test_discovery_preserves_changed_policy_and_selects_every_full_fork(self):
        self.assertEqual(N.discover(self.root,False)[0]['selected_forks'],[])
        selection=N.discover(self.root,True)[0]
        self.assertEqual(selection['selected_forks'],['karst']);self.assertEqual(selection['excluded'],[])
        self.assertEqual(selection['entries']['karst']['historical_tools'],{'forge':'1.2.3','just':'1.46.0'})
        path=self.root/'op-core/nuts/bundles/jovian_nut_bundle.json';path.write_bytes(self.bundle)
        self.write_locks({'karst':self.entry,'jovian':self.entry|{'bundle':str(path.relative_to(self.root))}})
        self.assertEqual(N.discover(self.root,False)[0]['selected_forks'],['jovian'])
        self.assertEqual(N.discover(self.root,True)[0]['selected_forks'],['jovian','karst'])
        self.git(self.root,'update-ref','-d','refs/remotes/origin/develop')
        fallback=N.discover(self.root,False)[0]
        self.assertFalse(fallback['base_lock_available']);self.assertEqual(fallback['selected_forks'],['jovian','karst'])

    def test_discovery_rejects_empty_missing_corrupt_and_unpinned_sources(self):
        for change in ('empty','missing-bundle','bad-hash','bad-commit','unsafe','duplicate-bundle','extra-setting'):
            entry=copy.deepcopy(self.entry)
            if change=='missing-bundle':entry['bundle']='op-core/nuts/bundles/missing.json'
            elif change=='bad-hash':entry['hash']='sha256:'+'0'*64
            elif change=='bad-commit':entry['commit']='0'*40
            elif change=='unsafe':entry['bundle']='op-core/nuts/bundles/../../foreign.json'
            elif change=='extra-setting':entry['override']='not-authoritative'
            entries={} if change=='empty' else {'karst':entry}
            if change=='duplicate-bundle':entries['jovian']=dict(entry)
            self.write_locks(entries)
            with self.subTest(change=change),self.assertRaises((ValueError,FileNotFoundError,subprocess.CalledProcessError)):
                N.discover(self.root,True)

    def report(self,directory,provider):
        directory.mkdir(parents=True);selection,current,base,error,historical=N.discover(self.root,True)
        N.S.write(directory/'selection.json',selection)
        N.S.write(directory/'settings.json',{'source_sha':self.sha,'branch':'codex/rwx-ci-pilot','input_sha256':N.M.inputs(),
                    'environment':{},'go_version':'fixture Go','prepare_only':False,'provider':provider})
        for name,data in [('fork_lock.toml',current),('base-fork-lock.toml',base),('base-discovery.stderr',error)]:
            (directory/name).write_bytes(data)
        fork=directory/'forks/karst';raw=fork/'originals';raw.mkdir(parents=True)
        entry=selection['entries']['karst']
        N.S.write(fork/'generation.stage.json',{'exit_code':0,'argv':N.prefix(entry['historical_tools'])+['go','run','./ops/scripts/nut-provenance-verify','karst']})
        (fork/'generation.log').write_text('Compiling 1 files with Solc 0.8.15\nPASS: bundle hash matches lock\nPASS: regenerated bundle matches committed bundle\n')
        N.S.write(raw/'source.json',{'fork':'karst','entry':{k.title():self.entry[k] for k in self.entry},'generator_argv':['just','generate-nut-bundle']})
        for name,path in [('mise.toml','mise.toml'),('contracts.justfile','packages/contracts-bedrock/justfile'),('foundry.toml','packages/contracts-bedrock/foundry.toml')]:
            (raw/name).write_bytes((self.root/path).read_bytes())
        for name in ('locked-bundle.json','regenerated-bundle.json'):(raw/name).write_bytes(self.bundle)
        (raw/'tracked-stage.bin').write_bytes(self.index);(raw/'worktree-status.txt').write_bytes(b'')
        module='packages/contracts-bedrock/lib/fixture';nested=module+'/lib/nested'
        (raw/'submodules.txt').write_text(' '+self.library_sha+' '+module+'\n '+self.nested_sha+' '+nested+'\n-'+self.library_sha+' rollup-boost\n')
        N.S.write(raw/'submodule-inventories.json',{name:{'head':sha,'tracked_stage':base64.b64encode(subprocess.check_output(['git','ls-files','--stage','-z'],cwd=root)).decode(),'status':''}
            for name,root,sha in [(module,self.library,self.library_sha),(nested,self.nested,self.nested_sha)]})
        N.S.write(fork/'tools.json',{name:{'version':version,'binary_sha256':'b'*64,'binary_path':'/'+provider+'/'+name}
            for name,version in [('forge','forge Version: 1.2.3-v1.2.3'),('just','just 1.46.0'),('go','fixture Go')]})
        N.S.write(fork/'compilers.json',{'0.8.15':{'version':'Version: 0.8.15+fixture','binary_sha256':'d'*64,'binary_path':'/'+provider+'/solc'}})
        self.reseal(directory);return directory

    def reseal(self,directory):
        hashes={k:v for k,v in N.seal(directory).items() if k!='final.json'}
        N.S.write(directory/'final.json',{'exit_code':0,'report_errors':[],'tests':0,'original_sha256':hashes})

    def test_complete_originals_compare_all_gitlinks_and_actual_generated_bytes(self):
        a=self.report(self.temp/'circle','circleci');b=self.report(self.temp/'native','rwx');out=self.temp/'comparison.json'
        self.assertEqual(N.compare(a,b,out),0)
        coverage=N.G.read(out)['coverage']['karst'];self.assertEqual(coverage['submodules'],3)
        self.assertEqual(coverage['outcome'],'passed');self.assertEqual(coverage['tests'],0)
        # Only the manifest-established empty file may be recovered from Circle.
        (a/'forks/karst/originals/worktree-status.txt').unlink()
        self.assertEqual(N.compare(a,b,out),0)
        (b/'forks/karst/originals/worktree-status.txt').unlink()
        self.assertEqual(N.compare(a,b,out),1)

    def test_full_selection_retains_unused_base_observations_and_rejects_incomplete_replays(self):
        a=self.report(self.temp/'circle','circleci')
        self.git(self.root,'update-ref','-d','refs/remotes/origin/develop')
        b=self.report(self.temp/'native','rwx');out=self.temp/'comparison.json'
        self.assertEqual(N.compare(a,b,out),0)
        original=N.G.read(b/'selection.json');record=N.G.read(out)['base_discovery']
        self.assertTrue(record['circleci']['base_lock_available']);self.assertFalse(record['rwx']['base_lock_available'])
        self.assertFalse(record['circleci']['affects_full_selection']);self.assertFalse(record['rwx']['affects_full_selection'])
        self.assertEqual(record['rwx']['stderr_sha256'],N.S.digest(b/'base-discovery.stderr'))
        for changed in (original|{'mode':'changed'},original|{'selected_forks':[]},
                        original|{'selected_forks':['karst','karst']},original|{'excluded':[{'fork':'karst'}]},
                        original|{'base_lock_available':True},original|{'base_revision':'foreign-ref'},
                        original|{'base_lock_exit_code':-15},original|{'base_lock_exit_code':256},
                        original|{'base_lock_available':1},
                        original|{'base_lock_available':True,'base_lock_exit_code':0,'base_revision':None},
                        original|{'entries':{'karst':original['entries']['karst']|{'commit':'c'*40}}}):
            N.S.write(b/'selection.json',changed);self.reseal(b)
            with self.subTest(changed=changed):self.assertEqual(N.compare(a,b,out),1)
        N.S.write(b/'selection.json',original);self.reseal(b)
        self.assertEqual(N.compare(a,b,out),0)

