    def executor(self,argv,**kwargs):
        selection=N.discover(self.root,True);selection[0]['go_argv']=argv
        command=N.command
        def call(*args,**params):return 'fixture Go' if args==('go','version') else command(*args,**params)
        stage=N.S.stage
        def run(directory,name,args,**params):return 0 if name in ('tool-prepare','compiler-prepare') else stage(directory,name,args,**params)
        with patch.dict(os.environ,self.env),patch.object(N,'command',side_effect=call),patch.object(N,'discover',return_value=selection),\
                patch.object(N,'prefix',return_value=[]),patch.object(N,'tool_identity',return_value={}),patch.object(N,'compiler_identity',return_value=None),patch.object(N.S,'stage',side_effect=run):
            result=N.execute('circleci',True,**kwargs)
        directory=self.root/'.ci/nut-provenance/run'
        return result,directory,N.G.read(directory/'final.json')

    def test_actual_successful_process_with_invalid_reports_returns_failure(self):
        result,directory,final=self.executor([sys.executable,'-c',"print('actual successful fixture subprocess')"])
        self.assertEqual(result,1);self.assertEqual(final['exit_code'],1);self.assertTrue(final['report_errors'])
        self.assertEqual(N.G.read(directory/'forks/karst/generation.stage.json')['exit_code'],0)
        self.assertTrue(final['original_sha256'])

    def test_actual_tool_stdout_stays_distinct_from_original_stderr_diagnostics(self):
        directory=self.temp/'streams';directory.mkdir()
        argv=[sys.executable,'-c',"import sys;print('go version fixture');print('mise WARN missing unrelated tool',file=sys.stderr)"]
        self.assertEqual(N.S.stage(directory,'identity',argv,cwd=str(directory),stdout_file='version.txt'),0)
        self.assertEqual((directory/'version.txt').read_text(),'go version fixture\n')
        self.assertEqual((directory/'identity.log').read_text(),'mise WARN missing unrelated tool\n')
        stage=N.G.read(directory/'identity.stage.json');self.assertEqual(stage['stdout_sha256'],N.S.digest(directory/'version.txt'))
        self.assertEqual(stage['log_sha256'],N.S.digest(directory/'identity.log'))
        with self.assertRaises(ValueError):N.S.stage(directory,'unsafe',argv,stdout_file='../outside')

    def test_actual_failure_and_cancellation_retain_original_status_and_partial_logs(self):
        result,directory,final=self.executor([sys.executable,'-c',"print('intentional original failure');raise SystemExit(17)"])
        self.assertEqual(result,17);self.assertEqual(final['exit_code'],17)
        marker=self.temp/'ready'
        def cancel():
            deadline=time.monotonic()+10
            while not marker.exists() and time.monotonic()<deadline:time.sleep(.02)
            os.kill(os.getpid(),signal.SIGTERM)
        thread=threading.Thread(target=cancel);thread.start()
        result,directory,final=self.executor([sys.executable,'-c',"import pathlib,time;pathlib.Path("+repr(str(marker))+").write_text('ready');print('original partial output',flush=True);time.sleep(30)"])
        thread.join();self.assertEqual(result,143);self.assertEqual(final['exit_code'],143)
        self.assertEqual(N.G.read(directory/'forks/karst/generation.stage.json')['exit_code'],-signal.SIGTERM)
        self.assertIn('original partial output',(directory/'forks/karst/generation.log').read_text())
        self.assertTrue(final['original_sha256'])


