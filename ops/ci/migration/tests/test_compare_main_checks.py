#!/usr/bin/env python3
"""Reject matching omissions, wrong commands and corrupt original Main reports."""
import importlib.util
import json
from pathlib import Path
import tempfile
import unittest
import xml.etree.ElementTree as ET

SPEC = importlib.util.spec_from_file_location('compare_main', Path(__file__).resolve().parents[2] / 'migration' / 'compare-main-checks.py')
COMPARE = importlib.util.module_from_spec(SPEC); SPEC.loader.exec_module(COMPARE)
SHA = 'a' * 40


class OriginalMainTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory(); self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name); self.directories = {}

    def write(self, path, value):
        path.parent.mkdir(parents=True, exist_ok=True)
        COMPARE.MAIN.STAGES.write(path, value)

    def seal(self, directory):
        self.write(directory / 'final.json', {'exit_code':0,'report_errors':[],
            'original_sha256':{str(p.relative_to(directory)):COMPARE.MAIN.STAGES.digest(p)
                               for p in directory.rglob('*') if p.is_file() and p.name != 'final.json'}})

    def fixture(self, job):
        self.job = job
        for provider in ('circle','rwx'):
            directory = self.root / provider; directory.mkdir(); self.directories[provider] = directory
            settings = {'source_sha':SHA,'job':job,'provider':'circleci' if provider == 'circle' else 'rwx',
                'branch':'pilot','workspace_root':'/' + provider,'tools':{'go':'go1.26.6','just':'pinned','jq':'pinned','yq':'pinned'},
                'input_sha256':{'ops/ci/runtime/main-checks.py':'b' * 64},
                'rwx_run_id':'fresh-original','rwx_task_attempt':'1'}
            selection, source, commands = {}, {}, {'check':(['bash','.circleci/scripts/check-l2-chains-sync.sh'] if job=='l2-chains-sync-check' else COMPARE.MAIN.COMMANDS[job])}
            def original(name, argv, data=None):
                relative = COMPARE.MAIN.MOCKS[job] if job in COMPARE.MAIN.MOCKS and name in ('packages','generators') else 'op-deployer' if job == 'op-deployer-forge-version' and name == 'check' else ''
                self.write(directory / (name + '.stage.json'), {'argv':argv, 'exit_code':0,'stdin':'devnull',
                    'cwd':str(Path(settings['workspace_root']) / relative)})
                (directory / (name + '.log')).write_text('')
                if data is not None:
                    if isinstance(data, str): (directory / (name + '.json')).write_text(data)
                    else: self.write(directory / (name + '.json'), data)
            if job in COMPARE.MAIN.GO_JOBS:
                commands['go-env'] = ['go','env','-json','GOOS','GOARCH','CGO_ENABLED','GOFLAGS','GOTOOLCHAIN']
                settings['go_environment'] = {'GOOS':'linux','GOARCH':'amd64','CGO_ENABLED':'1','GOFLAGS':'','GOTOOLCHAIN':'auto'}
                original('go-env', commands['go-env'], settings['go_environment'])
            if job in COMPARE.MAIN.MOCKS:
                component = COMPARE.MAIN.MOCKS[job]
                source = {component + '/input.go':'package input\n//go:generate mockery --name Input\n',
                          component + '/input_test.go':'package input\n//go:generate echo test-input\n',
                          component + '/mocks/input.go':'// Code generated by mockery. DO NOT EDIT.\npackage mocks\n'}
                rows = [{'ImportPath':'fixture/' + component, 'Dir':settings['workspace_root'] + '/' + component,
                         'GoFiles':['input.go'],'TestGoFiles':['input_test.go'],'IgnoredGoFiles':['excluded.go']},
                        {'ImportPath':'fixture/' + component + '/mocks','Dir':settings['workspace_root'] + '/' + component + '/mocks','GoFiles':['input.go']}]
                commands.update(packages=['go','list','-tags=generate','-json','./...'], generators=['go','generate','-n','-v','./...'])
                original('packages', commands['packages'], '\n'.join(json.dumps(r) for r in rows))
                original('generators', commands['generators'])
                (directory / 'generators.log').write_text('input.go\nmockery --name Input\ninput_test.go\necho test-input\n')
                dependencies = directory / 'dependencies'; dependencies.mkdir()
                bundle = dependencies / 'superchain-configs.zip'; bundle.write_bytes(b'original pinned bundle')
                digest = COMPARE.MAIN.STAGES.digest(bundle); pin = dependencies / 'superchain-configs.zip.sha256'
                pin.write_text(digest + '  superchain-configs.zip\n')
                settings['input_sha256'].update({name:'d'*64 for name in COMPARE.MAIN.BUNDLE_INPUTS})
                settings['input_sha256'][COMPARE.MAIN.BUNDLE + '.sha256'] = COMPARE.MAIN.STAGES.digest(pin)
                settings['input_sha256']['superchain-registry'] = {'gitlink':'e'*40}
                binding = {'source_sha':SHA,'registry_revision':'e'*40,'sha256':digest,'expected_sha256':digest,
                           'input_sha256':{name:settings['input_sha256'][name] for name in COMPARE.MAIN.BUNDLE_INPUTS},
                           'tools':settings['tools']}
                commands['superchain'] = ['just','build-superchain-go']; original('superchain',commands['superchain'])
                if provider == 'rwx':
                    prep = directory / 'producer'; prep.mkdir()
                    self.write(prep / 'bundle.json', binding); self.write(prep / 'coverage.json', {'tests':0,'verified_bundle':True})
                    self.write(prep / 'superchain.stage.json',json.loads((directory / 'superchain.stage.json').read_text()))
                    (prep / 'superchain.log').write_text('verified bundle')
                    self.write(prep / 'manifest.json', {'exit_code':0,'report_errors':[],
                        'original_sha256':{p.name:COMPARE.MAIN.STAGES.digest(p) for p in prep.iterdir()}})
            elif job == 'l2-chains-sync-check':
                source = {'.circleci/continue/main.yml':'original yaml\n','.circleci/l2-rpcs.json':'{"op-mainnet":{}}\n'}
                config = {'workflows':{'scheduled-daily-tests':{'jobs':[{'contracts-bedrock-tests-l2-fork':{'matrix':{'parameters':{'fork_op_chain':['op-mainnet']}}}}]}}}
                commands['configuration'] = ['yq','-o=json','.','.circleci/continue/main.yml']
                original('configuration',commands['configuration'],config)
                selection = COMPARE.E.helper('l2-chains-sync-check').l2_selection(config, {'op-mainnet':{}})
            elif job == 'op-deployer-forge-version':
                source = {'mise.toml':'[tools]\nforge = "1.8.3"\n','op-deployer/pkg/deployer/forge/version.json':'{"forge":"v1.8.3"}\n'}
                commands['mise-config'] = ['yq','-o=json','.','mise.toml']
                original('mise-config',commands['mise-config'],{'tools':{'forge':'1.8.3'}})
                selection = {'mise_forge':'1.8.3','deployer':{'forge':'v1.8.3'}}
            elif job == 'check-op-geth-version':
                source = {'go.mod':'module fixture\n'}
                commands['go-mod'] = ['go','mod','edit','-json']
                selection = {'Module':{'Path':'fixture'},'Require':[]}
                original('go-mod',commands['go-mod'],selection)
            elif job == 'check-nut-locks':
                source = {'op-core/nuts/fork_lock.toml':'[fork]\nbundle = "op-core/nuts/bundles/fork_nut_bundle.json"\n',
                          'op-core/nuts/bundles/fork_nut_bundle.json':'{}\n','op-core/nuts/state/fork_state.json':'{}\n'}
                commands['fetch-develop'] = ['git','fetch','--no-tags','origin','+refs/heads/develop:refs/remotes/origin/develop']
                original('fetch-develop',commands['fetch-develop'])
            else:
                selection = {'files':['complete.txt'],'todos':[],'near_misses':[],'check_closed':False}
                commands.update(COMPARE.MAIN.TODO_DISCOVERY)
                for name, argv in COMPARE.MAIN.TODO_DISCOVERY.items(): original(name,argv)
                (directory / 'files.log').write_text('complete.txt\n')
            for name, text in source.items():
                p = directory / 'source' / name; p.parent.mkdir(parents=True, exist_ok=True); p.write_text(text)
                settings['input_sha256'][name] = COMPARE.MAIN.STAGES.digest(p)
            if job in COMPARE.MAIN.MOCKS:
                selected = COMPARE.MAIN.packages((directory / 'packages.json').read_text(),component,settings['workspace_root'],directory / 'source')
                before = {component + '/mocks/input.go':settings['input_sha256'][component + '/mocks/input.go']}
                selection = {'component':component,'packages':selected,'generated_before':before,'superchain':binding}
                self.write(directory / 'generated.json', before)
            elif job == 'check-nut-locks': selection = COMPARE.MAIN.nut_selection(directory / 'source','c' * 40)
            original('check',commands['check'])
            self.write(directory / 'settings.json',settings); self.write(directory / 'selection.json',selection)
            self.write(directory / 'inputs-after.json',settings['input_sha256'])
            self.write(directory / 'coverage.json',{'job':job,'outcome':'pass','attempts':1,'complete_selection':True,'command':(['bash','.circleci/scripts/check-l2-chains-sync.sh'] if job=='l2-chains-sync-check' else COMPARE.MAIN.COMMANDS[job])})
            suite = ET.Element('testsuite',name='main-checks',tests='1',failures='0')
            ET.SubElement(suite,'testcase',name=job,classname='main-checks'); ET.ElementTree(suite).write(directory / 'check.junit.xml')
            self.seal(directory)

    def compare(self): return COMPARE.compare(self.directories,self.job,SHA)

    def test_all_seven_original_main_job_reports_match(self):
        for job in COMPARE.MAIN.COMMANDS:
            with self.subTest(job=job):
                self.root = Path(self.tmp.name) / job; self.root.mkdir(); self.fixture(job)
                self.assertTrue(self.compare()['verified_parity'])

    def test_same_wrong_original_command_is_rejected(self):
        self.fixture('check-generated-mocks-op-node')
        for d in self.directories.values():
            p=d/'check.stage.json';row=json.loads(p.read_text());row['argv']=['true'];self.write(p,row);self.seal(d)
        with self.assertRaisesRegex(ValueError,'command'): self.compare()

    def test_missing_test_file_directive_is_rejected_on_both_providers(self):
        self.fixture('check-generated-mocks-op-node')
        for d in self.directories.values():
            p=d/'selection.json';row=json.loads(p.read_text());row['packages'][0]['directives']=row['packages'][0]['directives'][:1];self.write(p,row);self.seal(d)
        with self.assertRaisesRegex(ValueError,'directives'): self.compare()

    def test_original_generation_source_corruption_cannot_be_resealed_as_success(self):
        self.fixture('check-generated-mocks-op-node')
        d=self.directories['rwx'];(d/'source/op-node/input.go').write_text('changed input');self.seal(d)
        with self.assertRaisesRegex(ValueError,'source bytes'): self.compare()

    def test_duplicate_or_failed_original_package_discovery_is_rejected(self):
        self.fixture('check-generated-mocks-op-node')
        d=self.directories['rwx'];p=d/'packages.json';p.write_text(p.read_text() + '\n' + p.read_text());self.seal(d)
        with self.assertRaisesRegex(ValueError,'duplicate'): self.compare()

    def test_missing_input_or_changed_generated_mock_is_rejected(self):
        self.fixture('check-generated-mocks-op-service')
        d=self.directories['rwx'];self.write(d/'generated.json',{});self.seal(d)
        with self.assertRaisesRegex(ValueError,'mocks changed'): self.compare()

    def test_corrupt_or_missing_nonempty_originals_are_rejected(self):
        self.fixture('check-op-geth-version')
        (self.directories['rwx']/'go-mod.json').write_text('{}')
        with self.assertRaisesRegex(ValueError,'corrupt'): self.compare()

    def test_only_manifest_declared_empty_circle_logs_can_be_restored(self):
        self.fixture('op-deployer-forge-version')
        (self.directories['circle']/'check.log').unlink()
        self.assertEqual(len(self.compare()['manifest_declared_empty_logs']),1)
        (self.directories['rwx']/'check.log').unlink()
        with self.assertRaises(OSError): self.compare()

    def test_stale_sha_reused_native_verdict_and_different_tool_are_rejected(self):
        self.fixture('check-op-geth-version')
        d=self.directories['rwx'];p=d/'settings.json';original=json.loads(p.read_text())
        for key,value in [('source_sha','b'*40),('rwx_run_id',None),('rwx_task_attempt','2'),('tools',{'go':'different'})]:
            row={**original,key:value};self.write(p,row);self.seal(d)
            with self.subTest(key=key), self.assertRaises(ValueError): self.compare()

    def test_matching_omitted_nut_bundle_is_rejected(self):
        self.fixture('check-nut-locks')
        for d in self.directories.values():
            p=d/'selection.json';row=json.loads(p.read_text());row['bundles']={};self.write(p,row);self.seal(d)
        with self.assertRaisesRegex(ValueError,'NUT selection'): self.compare()

    def test_matching_omitted_l2_chain_is_rejected(self):
        self.fixture('l2-chains-sync-check')
        for d in self.directories.values():
            p=d/'selection.json';row=json.loads(p.read_text());row['matrix_chains']=[];self.write(p,row);self.seal(d)
        with self.assertRaisesRegex(ValueError,'L2 chain'): self.compare()

    def test_forge_pin_and_protected_develop_drift_require_investigation(self):
        self.fixture('op-deployer-forge-version')
        d=self.directories['rwx'];p=d/'selection.json';row=json.loads(p.read_text());row['mise_forge']='changed';self.write(p,row);self.seal(d)
        with self.assertRaisesRegex(ValueError,'Forge version'): self.compare()
        self.root = Path(self.tmp.name) / 'nuts';self.root.mkdir();self.fixture('check-nut-locks')
        d=self.directories['rwx'];p=d/'selection.json';row=json.loads(p.read_text());row['develop_sha']='d'*40;self.write(p,row);self.seal(d)
        with self.assertRaisesRegex(ValueError,'parity'): self.compare()

    def test_failed_or_cancelled_original_is_not_replaced_by_passing_wrapper(self):
        self.fixture('check-op-geth-version')
        d=self.directories['rwx'];p=d/'check.stage.json';row=json.loads(p.read_text());row['exit_code']=-15;self.write(p,row);self.seal(d)
        with self.assertRaisesRegex(ValueError,'failed original'): self.compare()
        p=d/'final.json';row=json.loads(p.read_text());row['exit_code']=143;self.write(p,row)
        with self.assertRaisesRegex(ValueError,'Failed'): self.compare()

    def test_missing_stages_unexplained_retry_and_wrong_nested_cwd_are_rejected(self):
        self.fixture('op-deployer-forge-version')
        d=self.directories['rwx'];p=d/'check.stage.json';row=json.loads(p.read_text());row['cwd']='/rwx';self.write(p,row);self.seal(d)
        with self.assertRaisesRegex(ValueError,'command'): self.compare()
        row['cwd']='/rwx/op-deployer';self.write(p,row)
        self.write(d/'retry.stage.json',row);self.seal(d)
        with self.assertRaisesRegex(ValueError,'retry'): self.compare()

    def test_corrupt_original_superchain_cannot_be_resealed_as_passing(self):
        self.fixture('check-generated-mocks-op-node')
        d=self.directories['rwx'];(d/'dependencies/superchain-configs.zip').write_bytes(b'corrupt bundle');self.seal(d)
        with self.assertRaisesRegex(ValueError,'pinned superchain'):self.compare()

    def test_stale_producer_binding_and_nonzero_warm_tests_are_rejected(self):
        self.fixture('check-generated-mocks-op-node')
        d=self.directories['rwx'];p=d/'producer/bundle.json';row=json.loads(p.read_text());row['source_sha']='b'*40;self.write(p,row)
        manifest=json.loads((d/'producer/manifest.json').read_text());manifest['original_sha256']['bundle.json']=COMPARE.MAIN.STAGES.digest(p)
        self.write(d/'producer/manifest.json',manifest);self.seal(d)
        with self.assertRaisesRegex(ValueError,'reusable superchain binding'):self.compare()
        row['source_sha']=SHA;self.write(p,row);manifest['original_sha256']['bundle.json']=COMPARE.MAIN.STAGES.digest(p)
        p=d/'producer/coverage.json';self.write(p,{'tests':1,'verified_bundle':True});manifest['original_sha256']['coverage.json']=COMPARE.MAIN.STAGES.digest(p)
        self.write(d/'producer/manifest.json',manifest);self.seal(d)
        with self.assertRaisesRegex(ValueError,'reusable superchain binding'):self.compare()


if __name__ == '__main__': unittest.main()
