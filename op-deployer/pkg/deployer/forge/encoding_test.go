package forge

import (
	"math/big"
	"reflect"
	"testing"

	"github.com/ethereum/go-ethereum/accounts/abi"
	"github.com/ethereum/go-ethereum/common"
	"github.com/stretchr/testify/require"
)

type nestedTupleProposal struct {
	Root             common.Hash
	L2SequenceNumber *big.Int
}

type nestedTupleInput struct {
	StartingAnchorRoot nestedTupleProposal
}

type conversionTarget struct {
	First  uint64
	Second uint64
}

type nestedConversionTarget struct {
	Nested conversionTarget
}

func TestBytesScriptEncoderNestedTupleGolden(t *testing.T) {
	input := nestedTupleInput{StartingAnchorRoot: nestedTupleProposal{
		Root:             common.HexToHash("0x02f4397b2de6fce03b3f9982378c2b4c4deff9c92c662dcc6f9643267aeb5e47"),
		L2SequenceNumber: big.NewInt(1234),
	}}
	encoded, err := (&BytesScriptEncoder[nestedTupleInput]{TypeName: "nestedTupleInput"}).Encode(input)
	require.NoError(t, err)

	// Generated by abi.encode for the Solidity tuple shape ((bytes32,uint256)).
	const expected = "0x02f4397b2de6fce03b3f9982378c2b4c4deff9c92c662dcc6f9643267aeb5e47" +
		"00000000000000000000000000000000000000000000000000000000000004d2"
	require.Equal(t, common.FromHex(expected), encoded)
}

func TestBytesScriptDecoderNestedTuple(t *testing.T) {
	input := nestedTupleInput{StartingAnchorRoot: nestedTupleProposal{
		Root:             common.HexToHash("0x02f4397b2de6fce03b3f9982378c2b4c4deff9c92c662dcc6f9643267aeb5e47"),
		L2SequenceNumber: big.NewInt(1234),
	}}
	encoded, err := (&BytesScriptEncoder[nestedTupleInput]{TypeName: "nestedTupleInput"}).Encode(input)
	require.NoError(t, err)

	decoded, err := (&BytesScriptDecoder[nestedTupleInput]{TypeName: "nestedTupleInput"}).Decode(encoded)
	require.NoError(t, err)
	require.Equal(t, input.StartingAnchorRoot.Root, decoded.StartingAnchorRoot.Root)
	require.Zero(t, input.StartingAnchorRoot.L2SequenceNumber.Cmp(decoded.StartingAnchorRoot.L2SequenceNumber))
}

func TestConvertAnonStructToTypedRejectsMissingTopLevelField(t *testing.T) {
	anonStruct := struct {
		First uint64
	}{First: 1}

	_, err := ConvertAnonStructToTyped[conversionTarget](anonStruct)
	require.ErrorContains(t, err, "struct field count mismatch: source has 1 fields, target has 2 fields")
}

func TestConvertAnonStructToTypedRejectsMissingNestedField(t *testing.T) {
	anonStruct := struct {
		Nested struct {
			First uint64
		}
	}{Nested: struct{ First uint64 }{First: 1}}

	_, err := ConvertAnonStructToTyped[nestedConversionTarget](anonStruct)
	require.ErrorContains(t, err, "field Nested: struct field count mismatch: source has 1 fields, target has 2 fields")
}

func TestConvertAnonStructToTypedRejectsNonStructs(t *testing.T) {
	_, err := ConvertAnonStructToTyped[conversionTarget](uint64(1))
	require.EqualError(t, err, "both source and target must be structs")

	_, err = ConvertAnonStructToTyped[uint64](struct{ First uint64 }{First: 1})
	require.EqualError(t, err, "both source and target must be structs")
}

func TestGoStructToABITupleNestedTuple(t *testing.T) {
	tupleType, err := GoStructToABITuple(reflect.TypeFor[nestedTupleInput](), "nestedTupleInput")
	require.NoError(t, err)
	require.Len(t, tupleType.TupleElems, 1)
	require.Equal(t, []string{"StartingAnchorRoot"}, tupleType.TupleRawNames)
	require.Equal(t, "(bytes32,uint256)", tupleType.TupleElems[0].String())
	require.Equal(t, []string{"Root", "L2SequenceNumber"}, tupleType.TupleElems[0].TupleRawNames)

	args := abi.Arguments{{Type: tupleType}}
	tests := []struct {
		name     string
		proposal nestedTupleProposal
	}{
		{
			name: "zero sequence",
			proposal: nestedTupleProposal{
				Root:             common.Hash{0xde, 0xad},
				L2SequenceNumber: new(big.Int),
			},
		},
		{
			name: "non-zero sequence",
			proposal: nestedTupleProposal{
				Root:             common.HexToHash("0x02f4397b2de6fce03b3f9982378c2b4c4deff9c92c662dcc6f9643267aeb5e47"),
				L2SequenceNumber: big.NewInt(1234),
			},
		},
		{
			name: "maximum sequence",
			proposal: nestedTupleProposal{
				Root: common.HexToHash("0xffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffff"),
				L2SequenceNumber: new(big.Int).Sub(
					new(big.Int).Lsh(big.NewInt(1), 256),
					big.NewInt(1),
				),
			},
		},
	}

	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			input := nestedTupleInput{StartingAnchorRoot: test.proposal}
			expected, err := args.Pack(input)
			require.NoError(t, err)
			encoded, err := (&BytesScriptEncoder[nestedTupleInput]{TypeName: "nestedTupleInput"}).Encode(input)
			require.NoError(t, err)
			require.Equal(t, expected, encoded)

			unpacked, err := args.Unpack(encoded)
			require.NoError(t, err)
			require.Len(t, unpacked, 1)

			actual := *abi.ConvertType(unpacked[0], new(nestedTupleInput)).(*nestedTupleInput)
			require.Equal(t, input.StartingAnchorRoot.Root, actual.StartingAnchorRoot.Root)
			require.Zero(t, input.StartingAnchorRoot.L2SequenceNumber.Cmp(actual.StartingAnchorRoot.L2SequenceNumber))
		})
	}
}
