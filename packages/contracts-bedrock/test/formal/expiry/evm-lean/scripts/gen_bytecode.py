#!/usr/bin/env python3
"""Write ExpiryEvm/Bytecode.lean from bytecode/L2ToL2CrossDomainMessenger.runtime.hex.

The Lean file holds the exact deployed runtime bytes (metadata trailer included) as chunked
ByteArray literals, and its JUMPDEST table (computed here, checked in Lean by `native_decide`).
Rerun after recompiling the contract (scripts/regen.sh does):

    python3 scripts/gen_bytecode.py bytecode/L2ToL2CrossDomainMessenger.runtime.hex \
        ExpiryEvm/Bytecode.lean [defName]

`defName` (default `l2tol2Runtime`) names the ByteArray; its chunks are `<defName>Chunk<i>` and
its JUMPDEST theorem `<defName without "Runtime">ValidJumps`, so several contracts can share the namespace.
"""
import sys
from pathlib import Path

CHUNK = 1000


def main() -> None:
    src, dst = Path(sys.argv[1]), Path(sys.argv[2])
    name = sys.argv[3] if len(sys.argv) > 3 else "l2tol2Runtime"
    hexstr = src.read_text().strip()
    if hexstr.startswith("0x"):
        hexstr = hexstr[2:]
    code = bytes.fromhex(hexstr)
    chunks = [code[i:i + CHUNK] for i in range(0, len(code), CHUNK)]
    out = []
    out.append("import Ethereum.Semantics\nimport Reasoning.JumpDest\n")
    out.append("/-!\n# L2ToL2CrossDomainMessenger deployed runtime bytecode (generated)\n")
    out.append("Generated by `scripts/gen_bytecode.py` from")
    out.append("`bytecode/L2ToL2CrossDomainMessenger.runtime.hex`; do not edit by hand.\n")
    out.append(f"Size: {len(code)} bytes. See README.md for the compiler invocation and hashes.\n-/\n")
    out.append("namespace ExpiryEvm\n")
    out.append("set_option maxRecDepth 50000000\n")
    for i, ch in enumerate(chunks):
        body = ", ".join(f"0x{b:02x}" for b in ch)
        # wrap lines
        parts = body.split(", ")
        lines, cur = [], ""
        for p in parts:
            if len(cur) + len(p) + 2 > 96:
                lines.append(cur)
                cur = p
            else:
                cur = p if not cur else cur + ", " + p
        lines.append(cur)
        joined = ",\n    ".join(lines)
        out.append(f"def {name}Chunk{i} : ByteArray :=\n  ⟨#[{joined}]⟩\n")
    cat = " ++ ".join(f"{name}Chunk{i}" for i in range(len(chunks)))
    out.append("/-- The deployed runtime code of L2ToL2CrossDomainMessenger at the pinned commit. -/")
    out.append(f"def {name} : ByteArray :=\n  {cat}\n")
    # JUMPDEST analysis (positions of 0x5b outside PUSH immediates), as EVM D_J computes it.
    dests, i = [], 0
    while i < len(code):
        op = code[i]
        if op == 0x5B:
            dests.append(i)
        i += 1 + (op - 0x5F if 0x60 <= op <= 0x7F else 0)
    lst = ", ".join(f"⟨{d}⟩" for d in dests)
    out.append(f"/-- The JUMPDEST set of `{name}` (checked by `native_decide`, which runs the")
    out.append("    compiled `D_J`; kernel evaluation of the scan is too slow, see README). -/")
    out.append(f"@[valid_jumps] theorem {name.replace('Runtime', '')}ValidJumps :")
    out.append(f"    Ethereum.EVM.D_J {name} 0 = #[" + lst + "] := by")
    out.append("  native_decide\n")
    out.append("end ExpiryEvm\n")
    dst.write_text("\n".join(out))


if __name__ == "__main__":
    main()
